"""BS 账户决策纯政策内核（W2）的稳定窄公共入口。

W2 只做**纯计算**：读取 W1 冻结证据与调用方提供的只读账户/行情 view，输出
可审计的:class:`DecisionBundle`（候选政策、逐项拒绝原因、共同场景矩阵、EV/
Hurwicz/敏感性、选中计划、动作上限、下一观察条件、恢复状态）。它不读时钟 /
env / 数据库，不执行交易，也不写任何账本；W3 才负责批次账本、订单与成交执行，
W4 负责研究入口与 Web 投影。

用法（调用方负责取数与冻结）::

    from dragon_quant.review_account.strategy import bs_policy

    config = bs_policy.BSPolicyConfig.from_dict(policy_json)
    bundle = bs_policy.evaluate_account_policy(bs_policy.PolicyContext(
        decision_time=cutoff,
        config=config,
        snapshot=snapshot,
        account=account_view,
        candidates=candidates,
        market=market_view,
        risk_envelope=envelope,
        scenarios=scenarios,
        probability=probability,
        recovery_state=recovery,
    ))
"""

